package io.github.lemcoder.index.exporter

import io.github.lemcoder.model.BundledLibraries

/**
 * The loader generated bindings use in place of a bare `System.loadLibrary`: the library from
 * `java.library.path` if it is there — so a build's own setup still wins — else from the jar's
 * `konan/natives/<target>/`, where the Konan plugin bundles each JVM target's library, extracted to a
 * temporary file. On Android the first step always succeeds: the library is in the APK.
 *
 * Written into each binding's package, so the bindings keep needing nothing at runtime. The resource
 * layout and the platform names are the plugin's (`konan/natives/` + Kotlin/Native target names).
 */
internal object NativeLoaderSource {
    private const val RESOURCE_ROOT = BundledLibraries.RESOURCE_ROOT

    /** A private top-level Kotlin function `loadNativeLibrary(name)`, for the JNI bindings' file. */
    fun kotlin(): String = """
        |/**
        | * Loads [name] from `java.library.path`, else from this jar's `$RESOURCE_ROOT/<target>/`, where the Konan
        | * plugin bundles it, through a temporary file.
        | */
        |private fun loadNativeLibrary(name: String) {
        |    try {
        |        System.loadLibrary(name)
        |    } catch (notOnPath: UnsatisfiedLinkError) {
        |        val os = System.getProperty("os.name").lowercase()
        |        val arch = when (System.getProperty("os.arch").lowercase()) {
        |            "aarch64", "arm64" -> "arm64"
        |            "amd64", "x86_64" -> "x64"
        |            else -> throw notOnPath
        |        }
        |        val target = when {
        |            os.contains("mac") || os.contains("darwin") -> "macos_${'$'}arch"
        |            os.contains("windows") -> "mingw_${'$'}arch"
        |            os.contains("linux") -> "linux_${'$'}arch"
        |            else -> throw notOnPath
        |        }
        |        val file = System.mapLibraryName(name)
        |        val input = java.lang.invoke.MethodHandles.lookup().lookupClass()
        |            .getResourceAsStream("/$RESOURCE_ROOT/${'$'}target/${'$'}file") ?: throw notOnPath
        |        val directory = java.nio.file.Files.createTempDirectory("konan-${'$'}name").toFile().apply { deleteOnExit() }
        |        val library = java.io.File(directory, file).apply { deleteOnExit() }
        |        input.use { from -> library.outputStream().use { from.copyTo(it) } }
        |        System.load(library.absolutePath)
        |    }
        |}
        |""".trimMargin()

    /** A package-private Java class `KonanNativeLoader` with `load(name)`, for jextract's output. */
    fun java(packageName: String): String = """
        |// Generated by the Konan plugin; do not edit.
        |${if (packageName.isEmpty()) "" else "package $packageName;\n"}
        |import java.io.File;
        |import java.io.InputStream;
        |import java.nio.file.Files;
        |import java.nio.file.StandardCopyOption;
        |
        |/**
        | * Loads a library from {@code java.library.path}, else from this jar's {@code $RESOURCE_ROOT/<target>/},
        | * where the Konan plugin bundles it, through a temporary file.
        | */
        |final class KonanNativeLoader {
        |    private KonanNativeLoader() {}
        |
        |    static void load(String name) {
        |        try {
        |            System.loadLibrary(name);
        |        } catch (UnsatisfiedLinkError notOnPath) {
        |            String os = System.getProperty("os.name").toLowerCase();
        |            String arch = switch (System.getProperty("os.arch").toLowerCase()) {
        |                case "aarch64", "arm64" -> "arm64";
        |                case "amd64", "x86_64" -> "x64";
        |                default -> throw notOnPath;
        |            };
        |            String target;
        |            if (os.contains("mac") || os.contains("darwin")) target = "macos_" + arch;
        |            else if (os.contains("windows")) target = "mingw_" + arch;
        |            else if (os.contains("linux")) target = "linux_" + arch;
        |            else throw notOnPath;
        |            String file = System.mapLibraryName(name);
        |            try (InputStream input = KonanNativeLoader.class.getResourceAsStream("/$RESOURCE_ROOT/" + target + "/" + file)) {
        |                if (input == null) throw notOnPath;
        |                File directory = Files.createTempDirectory("konan-" + name).toFile();
        |                directory.deleteOnExit();
        |                File library = new File(directory, file);
        |                library.deleteOnExit();
        |                Files.copy(input, library.toPath(), StandardCopyOption.REPLACE_EXISTING);
        |                System.load(library.getAbsolutePath());
        |            } catch (java.io.IOException e) {
        |                UnsatisfiedLinkError error = new UnsatisfiedLinkError("Could not extract " + file + ": " + e);
        |                error.addSuppressed(notOnPath);
        |                throw error;
        |            }
        |        }
        |    }
        |}
        |""".trimMargin()
}
